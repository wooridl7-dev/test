"""Tests for core.cookie_health and how run_download feeds it.

Every cookie value below is made up (``FAKE-...``). The real cookie file of
2026-10-05 held no login at all (only visitor cookies), so no real logged-in
file was available as a sample.

Run from the repo root with::

    python -m unittest

Standard library only.
"""

